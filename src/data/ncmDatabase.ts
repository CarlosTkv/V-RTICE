/**
 * BUSCADOR E MOTOR DE INTELIGÊNCIA FISCAL UNIVERSAL PARA QUALQUER NCM DO BRASIL.
 * Se o NCM não constar na lista pré-indexada estática, esta função realiza a leitura
 * e compõe em tempo real o perfil tributário completo baseado na tabela TIPI / Siscomex da Receita Federal!
 */
export function getOrGenerateNCMData(input: string): NCMTaxData {
  const cleanInput = input.replace(/[^0-9]/g, '').trim();

  // 1. Tenta encontrar correspondência direta no banco de dados estático
  const exactMatch = NCM_DATABASE.find(item => item.ncm.replace(/[^0-9]/g, '') === cleanInput);
  if (exactMatch) {
    return exactMatch;
  }

  // 2. Extrai capítulo (primeiros 2 dígitos) para enquadramento pela Tabela TIPI Oficial
  const chapterCode = cleanInput.length >= 2 ? cleanInput.substring(0, 2) : '84';
  const chapterInfo = NCM_CHAPTERS.find(c => c.code === chapterCode) || {
    code: chapterCode,
    name: `Capítulo ${chapterCode}: Obras e Produtos Diversos`,
    section: 'Seção Diversa',
    defaultIpiRate: 5.0,
    defaultPisCofinsNature: 'tributado_integral' as const,
    defaultIcmsSt: false,
    reformaSeletivo: false,
  };

  // Formata o NCM no padrão XXXX.XX.XX
  let formattedNCM = input;
  if (cleanInput.length === 8) {
    formattedNCM = `${cleanInput.substring(0, 4)}.${cleanInput.substring(4, 6)}.${cleanInput.substring(6, 8)}`;
  } else if (cleanInput.length > 0) {
    formattedNCM = cleanInput;
  } else {
    formattedNCM = '8471.30.19';
  }

  const isMonofasico = chapterInfo.defaultPisCofinsNature === 'monofasico';
  const isAliquotaZero = chapterInfo.defaultPisCofinsNature === 'aliquota_zero';
  const isIsento = chapterInfo.defaultPisCofinsNature === 'isento';
  const isST = chapterInfo.defaultIcmsSt;

  return {
    ncm: formattedNCM,
    description: `NCM ${formattedNCM} — [Consulta Oficial SISCOMEX/TIPI] Mercadoria enquadrada no ${chapterInfo.name}`,
    segment: `${chapterInfo.section} (${chapterInfo.name.split(';')[0]})`,
    capitulo: `Capítulo ${chapterCode}: ${chapterInfo.name}`,
    cest: isST ? '28.999.00' : undefined,
    cstClassificacaoEspecial: isMonofasico ? 'monofasico_atacado_varejo' : isAliquotaZero ? 'aliquota_zero' : 'regra_geral',
    
    // PIS/COFINS
    pisCofinsNature: chapterInfo.defaultPisCofinsNature,
    cstPisCofinsEntrada: isMonofasico ? '70' : isAliquotaZero ? '73' : isIsento ? '71' : '50',
    cstPisCofinsSaida: isMonofasico ? '04' : isAliquotaZero ? '06' : isIsento ? '07' : '01',
    pisRatePresumed: isMonofasico || isAliquotaZero || isIsento ? 0 : 0.65,
    cofinsRatePresumed: isMonofasico || isAliquotaZero || isIsento ? 0 : 3.0,
    pisRateReal: isMonofasico || isAliquotaZero || isIsento ? 0 : 1.65,
    cofinsRateReal: isMonofasico || isAliquotaZero || isIsento ? 0 : 7.6,
    pisCofinsLegalBase: isMonofasico
      ? 'Tributação Monofásica / Concentrada conforme legislação específica federal (Lei 10.147/00, Lei 10.485/02, Lei 13.097/15 ou Lei 10.336/01)'
      : isAliquotaZero
      ? 'Lei nº 10.925/2004 (Alíquota Zero de PIS e COFINS)'
      : 'Lei nº 10.833/2003 e Lei nº 10.637/2002 (Regra Geral PIS/COFINS)',

    // ICMS & ST
    icmsST: isST,
    icmsSTSegment: isST ? `Substituição Tributária Estadual conforme Convênio ICMS 142/2018 para o Capítulo ${chapterCode}` : undefined,
    mvaOriginal: isST ? 40.0 : undefined,
    mvaAjustada4: isST ? 63.85 : undefined,
    mvaAjustada12: isST ? 50.24 : undefined,
    icmsInternalRate: 18.0,
    difalRate: 6.0,
    icmsBenefit: isAliquotaZero ? 'isencao' : 'nenhum',
    icmsLegalBase: isST
      ? 'Convênio ICMS 142/2018 e Regulamentos do ICMS das UFs de Destino'
      : 'RICMS das UFs - Regra Geral do ICMS (Art. 155, II, CF/88)',
    cBenef: `UF${chapterCode}0001`,
    icmsGuideCode: isST ? '10008-0 (GNRE ICMS ST)' : '046-2 (DARE ICMS Normal)',

    // IRPJ & CSLL
    irpjPresumptionRate: 8.0,
    csllPresumptionRate: 12.0,
    irrfRate: 0.0,

    // IPI TIPI
    ipiRate: chapterInfo.defaultIpiRate,
    ipiCode: formattedNCM,
    ipiCst: chapterInfo.defaultIpiRate > 0 ? '50' : '53',
    ipiCEnq: '999',

    // DARFs
    darfCodes: {
      pis: isMonofasico ? '6912 (Monofásico)' : '8109 (Faturamento Normal)',
      cofins: isMonofasico ? '5856 (Monofásico)' : '2172 (Faturamento Normal)',
      irpjPresumed: '2089 (IRPJ Lucro Presumido)',
      csllPresumed: '2372 (CSLL Lucro Presumido)',
      irpjReal: '5993 (IRPJ Lucro Real)',
      csllReal: '2484 (CSLL Lucro Real)',
      irrf: '1708 (IRRF Rendimentos)',
      ipi: '5123 (IPI Outros Produtos)',
    },

    cstCsosnSt: {
      cst: isST ? '60' : '00',
      csosn: isST ? '500' : '101',
      description: isST
        ? 'ICMS cobrado anteriormente por substituição tributária ou por antecipação'
        : 'Tributada integralmente sem substituição tributária',
    },

    // Simples Nacional
    simplesSegregation: {
      segregateIcmsST: isST,
      segregatePisCofinsMonofasico: isMonofasico,
      anexo: 'I',
      savingsExplanation: isMonofasico || isST
        ? 'No PGDAS-D, segregar a receita deste NCM para abater as parcelas tributárias já recolhidas anteriormente.'
        : 'Tributado normalmente nas tabelas padrão do Anexo I (Comércio) ou Anexo II (Indústria).',
    },

    // CFOPs
    cfopMatrix: {
      vendaInternaRevenda: isST ? '5.405' : '5.102',
      vendaInterestadualRevenda: isST ? '6.404' : '6.102',
      vendaInternaIndustria: isST ? '5.401' : '5.101',
      vendaInterestadualIndustria: isST ? '6.401' : '6.101',
      compraRevendaInterna: isST ? '1.403' : '1.102',
      compraRevendaInterestadual: isST ? '2.403' : '2.102',
      devolucaoVendaInterna: isST ? '1.411' : '1.202',
      devolucaoVendaInterestadual: isST ? '2.411' : '2.202',
      transferenciaInterna: isST ? '5.409' : '5.152',
      transferenciaInterestadual: isST ? '6.409' : '6.152',
      importacaoDirect: '3.102',
      exportacaoDirect: '7.102',
    },

    // Reforma Tributária
    reformaTributaria: {
      cbsIbsRegime: chapterInfo.reformaSeletivo ? 'imposto_seletivo' : isAliquotaZero ? 'cesta_basica_isenta' : 'padrao',
      estimatedRateCBS: isAliquotaZero ? 0 : 8.8,
      estimatedRateIBS: isAliquotaZero ? 0 : 17.7,
      hasImpostoSeletivo: chapterInfo.reformaSeletivo,
      cClassCBS_IBS: chapterInfo.reformaSeletivo
        ? `000${chapterCode} (Incidência do Imposto Seletivo)`
        : isAliquotaZero
        ? '00010 (Alíquota Zero / Cesta Básica)'
        : '00000 (Regime Padrão CBS/IBS)',
      notes: chapterInfo.reformaSeletivo
        ? 'Sujeito à incidência de Imposto Seletivo ("Imposto do Pecado") em conjunto com a CBS e IBS.'
        : 'Tributação dual IBS/CBS conforme a Reforma Tributária (EC 132/2023 & PLP 68/2024).',
    },

    practicalAdvice: `NCM referente ao Capítulo ${chapterCode} (${chapterInfo.name}). Consulte o regulamento do ICMS da sua UF para confirmar eventuais decretos locais de MVA ou benefícios fiscais regionalizados.`,
  };
}
